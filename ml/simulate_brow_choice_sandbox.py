#!/usr/bin/env python3
"""Synthetic-only sandbox for the conditional three-candidate choice model.

Outputs conditional probabilities that sum to one for each natural/soft/defined choice
set. The synthetic labels and truth probabilities are generated by this file, so the
report is strictly a software/calibration check and never authorizes release.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from train_brow_choice_ranker import (
    CHOICE_FEATURE_NAMES,
    build_choice_sessions,
    feature_row,
    session_logits,
    softmax,
    train_choice_model,
)

STYLE_CANDIDATES = (
    ("natural", 1.00, 1.00, 0.92),
    ("soft", 0.82, 0.94, 0.72),
    ("defined", 1.18, 1.06, 1.22),
)
TRUE_WEIGHTS_BY_NAME = {
    "thickness": 0.60,
    "length": -0.22,
    "arch": 0.48,
    "style_soft": -0.28,
    "style_defined": 0.18,
    "face_width_height_x_thickness": 1.20,
    "face_width_height_x_length": -0.30,
    "face_width_height_x_arch": 0.80,
    "interocular_ratio_x_thickness": 0.70,
    "interocular_ratio_x_arch": 0.45,
    "jaw_ratio_x_arch": 0.60,
    "brow_eye_distance_x_thickness": -4.50,
    "brow_eye_distance_x_arch": 2.20,
    "brow_asymmetry_x_arch": -3.00,
    "face_width_height_x_style_soft": 0.60,
    "face_width_height_x_style_defined": -0.25,
    "brow_eye_distance_x_style_soft": 2.00,
    "brow_eye_distance_x_style_defined": -1.25,
    "brow_asymmetry_x_style_soft": 1.10,
    "brow_asymmetry_x_style_defined": -1.65,
    "eye_line_tilt_x_style_soft": 0.45,
    "eye_line_tilt_x_style_defined": 0.90,
    "native_brow_area_fraction_x_thickness": 0.75,
    "native_brow_side_imbalance_x_thickness": -0.90,
    "native_brow_side_imbalance_x_arch": -1.35,
}
TRUE_WEIGHTS = np.asarray(
    [TRUE_WEIGHTS_BY_NAME.get(name, 0.0) for name in CHOICE_FEATURE_NAMES],
    dtype=np.float64,
)


def make_synthetic_rows(
    case_count: int, prefix: str, seed: int
) -> tuple[list[dict[str, str]], dict[str, list[float]]]:
    rng = np.random.default_rng(seed)
    rows: list[dict[str, str]] = []
    true_probabilities: dict[str, list[float]] = {}
    for case_index in range(case_count):
        case_id = f"SYNTH-CHOICE-{prefix}-{case_index:04d}"
        session_id = f"{case_id}-SESSION-01"
        face_width_height = float(np.clip(rng.normal(0.78, 0.075), 0.60, 0.98))
        interocular = float(np.clip(rng.normal(0.38, 0.045), 0.25, 0.52))
        jaw_ratio = float(np.clip(rng.normal(0.80, 0.10), 0.55, 1.02))
        brow_eye = float(np.clip(rng.normal(0.055, 0.018), 0.015, 0.12))
        asymmetry = float(np.clip(rng.gamma(1.6, 0.012), 0.0, 0.09))
        eye_tilt = float(np.clip(rng.normal(0.0, 0.06), -0.18, 0.18))
        native_area = float(np.clip(rng.normal(0.12, 0.045), 0.01, 0.28))
        side_imbalance = float(np.clip(rng.normal(0.04, 0.025), 0.0, 0.18))
        mask_available = float(rng.random() < 0.82)
        native_shape_mode = float(rng.random() < 0.45)
        base_fields = {
            "case_id": case_id,
            "session_id": session_id,
            "face_width_height_ratio": f"{face_width_height:.8f}",
            "interocular_face_width_ratio": f"{interocular:.8f}",
            "jaw_face_width_ratio": f"{jaw_ratio:.8f}",
            "brow_eye_distance_ratio": f"{brow_eye:.8f}",
            "brow_asymmetry_ratio": f"{asymmetry:.8f}",
            "eye_line_tilt": f"{eye_tilt:.8f}",
            "native_brow_area_fraction": f"{native_area:.8f}",
            "native_brow_side_imbalance": f"{side_imbalance:.8f}",
            "native_brow_mask_available": f"{mask_available:.0f}",
            "native_shape_mode": f"{native_shape_mode:.0f}",
        }
        candidate_rows: list[dict[str, str]] = []
        for style, thickness, length, arch in STYLE_CANDIDATES:
            candidate_rows.append({
                **base_fields,
                "style": style,
                "thickness": f"{thickness:.8f}",
                "length": f"{length:.8f}",
                "arch": f"{arch:.8f}",
                "selected": "false",
            })
        candidate_features = np.stack([
            feature_row(row, source="synthetic generator", row_num=index + 2)
            for index, row in enumerate(candidate_rows)
        ])
        logits = candidate_features @ TRUE_WEIGHTS
        probabilities = softmax(logits, temperature=1.0)
        chosen = int(rng.choice(3, p=probabilities))
        for index, row in enumerate(candidate_rows):
            row["selected"] = "true" if index == chosen else "false"
        rows.extend(candidate_rows)
        true_probabilities[session_id] = probabilities.tolist()
    return rows, true_probabilities


def run_sandbox(seed: int = 2026) -> dict[str, Any]:
    dev_rows, _ = make_synthetic_rows(300, "DEV", seed)
    cal_rows, _ = make_synthetic_rows(90, "CAL", seed + 1)
    ext_rows, ext_truth = make_synthetic_rows(160, "EXT", seed + 2)
    development = build_choice_sessions(dev_rows, "synthetic development")
    calibration = build_choice_sessions(cal_rows, "synthetic calibration")
    external = build_choice_sessions(ext_rows, "synthetic external")
    model = train_choice_model(development, calibration, external, seed=seed)

    predicted: list[np.ndarray] = []
    truth: list[np.ndarray] = []
    sums: list[float] = []
    for session in external:
        probabilities = softmax(
            session_logits(session, np.asarray(model["means"]), np.asarray(model["scales"]),
                           np.asarray(model["coefficients"])),
            float(model["temperature"]),
        )
        predicted.append(probabilities)
        truth.append(np.asarray(ext_truth[session["session_id"]], dtype=np.float64))
        sums.append(abs(float(probabilities.sum()) - 1.0))
    metrics = model["external_validation"]
    probability_mae = float(np.mean(np.abs(np.stack(predicted) - np.stack(truth))))
    report = {
        "test_type": "synthetic_conditional_choice_calibration_not_real_customer_evidence",
        "seed": seed,
        "cases": {"development": 300, "calibration": 90, "external": 160},
        "sessions": {"development": len(development), "calibration": len(calibration), "external": len(external)},
        "external_metrics": metrics,
        "mean_absolute_probability_error_vs_known_synthetic_generator": probability_mae,
        "maximum_probability_sum_error": max(sums),
        "predicted_probability_range": [
            float(min(values.min() for values in predicted)),
            float(max(values.max() for values in predicted)),
        ],
        "release_approved": False,
        "note": (
            "Every generated session has three synthetic candidates and one sampled choice. "
            "The true probabilities come from this synthetic generator. These metrics validate "
            "software behavior only; do not use them as real customer probabilities or place "
            "this model into the Android assets."
        ),
    }
    if not np.isfinite(np.stack(predicted)).all():
        raise AssertionError("Conditional choice probabilities must be finite")
    if np.any(np.stack(predicted) < 0.0) or np.any(np.stack(predicted) > 1.0):
        raise AssertionError("Conditional choice probabilities must lie in [0,1]")
    if max(sums) > 1e-10:
        raise AssertionError("Probabilities within each choice set must sum to one")
    if metrics["top1_accuracy"] < 0.30:
        raise AssertionError("Conditional choice ranker failed the synthetic discrimination smoke check")
    if probability_mae >= 0.30:
        raise AssertionError("Conditional choice probability error is too large for the synthetic fixture")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--output", type=Path, default=Path("brow_choice_sandbox_report.json"))
    args = parser.parse_args()
    report = run_sandbox(args.seed)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    print(f"Synthetic conditional-choice report written to: {args.output}")


if __name__ == "__main__":
    main()
